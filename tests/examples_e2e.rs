//! End-to-end contract (PROMPT step 10): every example is built by the real `agentmark` binary,
//! compiled by cargo, and the resulting program is run from each fixture folder (the plain one and
//! every `variants/<case>/`, Q150/Q153) with `--once --mock --fixtures . --trace -`. The trace it
//! prints must equal `expected.trace.jsonl`, line by line, compared as parsed JSON.

mod support;

use std::path::{Path, PathBuf};
use std::process::Command;

use serde_json::Value;

use support::*;

/// Fails with a readable diff of the first differing trace line (and of any length mismatch).
fn assert_same_trace(label: &str, got: &[Value], want: &[Value]) {
    for (i, (g, w)) in got.iter().zip(want).enumerate() {
        if g != w {
            panic!(
                "{label}: trace line {} differs\n  expected: {w}\n  got:      {g}\n\nfull expected:\n{}\nfull got:\n{}",
                i + 1,
                lines(want),
                lines(got)
            );
        }
    }
    if got.len() != want.len() {
        panic!(
            "{label}: expected {} trace lines, got {}\n\nfull expected:\n{}\nfull got:\n{}",
            want.len(),
            got.len(),
            lines(want),
            lines(got)
        );
    }
}

fn lines(v: &[Value]) -> String {
    v.iter().enumerate().map(|(i, l)| format!("{:>3}  {l}\n", i + 1)).collect()
}

/// `agentmark build examples/<name> --target rust -o <tmp>` then `cargo build`; returns the program.
fn build_example(name: &str, project: &str) -> (Tmp, PathBuf) {
    let out = temp(&format!("e2e-{name}"));
    let o = agentmark(&["build", &format!("{ROOT}/examples/{name}"), "--target", "rust", "-o", s(&out)]).output().unwrap();
    assert!(o.status.success(), "{name}: agentmark build failed:\n{}", stderr(&o));
    let bin = build_bin(&out, project);
    (out, bin)
}

/// Runs the program from `dir` (the fixture folder is the working directory, Q153) and returns the
/// parsed trace it prints.
fn run_fixture(bin: &Path, label: &str, dir: &Path) -> Vec<Value> {
    let o = Command::new(bin).args(["--once", "--mock", "--fixtures", ".", "--trace", "-"]).current_dir(dir).output().unwrap();
    assert!(o.status.success(), "{label}: the program failed ({}):\n{}", o.status, stderr(&o));
    parse_lines(&stdout(&o))
}

fn e2e(name: &str, project: &str, expect_variants: &[&str]) {
    let fixtures = fixture_dirs_of(name);
    let variants: Vec<&str> = fixtures.iter().filter_map(|(l, _)| l.rsplit_once("/variants/").map(|(_, v)| v)).collect();
    assert_eq!(variants, expect_variants, "{name}: the fixture variants changed; cover them here");
    assert!(fixtures.iter().any(|(l, _)| l == name), "{name}: no main fixture");
    let (_out, bin) = build_example(name, project);
    for (label, dir) in &fixtures {
        let want = parse_lines(&std::fs::read_to_string(dir.join("expected.trace.jsonl")).unwrap());
        assert!(!want.is_empty(), "{label}: empty expected trace");
        let got = run_fixture(&bin, label, dir);
        assert_same_trace(label, &got, &want);
    }
}

