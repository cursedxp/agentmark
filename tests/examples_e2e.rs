/// The sha2 binding of 05 is generated by the binder exactly once and then served from the cache
/// (SPEC 15.2, Q137): build 05 without `bindings/sha2.agent.md` twice, counting the generations.
#[test]
fn the_sha2_binding_is_generated_once_then_cached() {
    let d = temp("e2e-sha2");
    let proj = d.join("invoice-service");
    copy_dir(Path::new(&format!("{ROOT}/examples/05-invoice-service")), &proj);
    std::fs::remove_file(proj.join("bindings/sha2.agent.md")).unwrap();
    assert!(!proj.join("bindings/sha2.agent.md").exists());
    let out = d.join("out");
    let build = || {
        let mut c = agentmark(&["build", s(&proj), "-o", s(&out), "--no-check"]);
        bind_env(&mut c);
        c.output().unwrap()
    };

    // the first build generates the binding and stops: nobody has approved its effect yet (Q190)
    let first = build();
    let e1 = stderr(&first);
    assert_eq!(first.status.code(), Some(1), "{e1}");
    assert!(e1.contains("binding sha2: generated"), "the first build generates the binding:\n{e1}");
    assert!(e1.contains("is unverified"), "{e1}");
    let binding = proj.join("bindings/sha2.agent.md");
    assert!(binding.is_file(), "the binding is written next to the code");
    // the author approves the one line, as the message says
    let text = std::fs::read_to_string(&binding).unwrap();
    assert!(text.contains("- effect: unverified"), "{text}");
    std::fs::write(&binding, text.replace("- effect: unverified", "- effect: pure")).unwrap();

    let second = build();
    let e2 = stderr(&second);
    assert!(second.status.success(), "second build failed:\n{e2}");
    assert!(e2.contains("binding sha2: cached"), "the second build serves it from the cache:\n{e2}");
    assert!(!e2.contains("binding sha2: generated"), "{e2}");
    assert_eq!(format!("{e1}{e2}").matches("binding sha2: generated").count(), 1, "generated exactly once");
}
