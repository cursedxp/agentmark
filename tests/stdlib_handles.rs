fn errors_of(lines: &[&str]) -> String {
    let body: String = lines.iter().map(|l| format!("{l}\n")).collect();
    let main = format!("# Import: crate sha2\n\n> Hashes.\n# Command: go\n- args: word: text\n\n## Run\n{body}");
    let p = Project::from_memory(
        "app/main.agent.md",
        vec![("app/main.agent.md", &main), ("app/bindings/sha2.agent.md", HASH_BINDING), ("app/tools.toml", "")],
    );
    match sema::check(&p) {
        Ok(_) => String::new(),
        Err(d) => p.render(&d.into_iter().filter(|x| x.severity == Severity::Error).collect::<Vec<_>>()),
    }
}

#[test]
fn a_handle_cannot_be_encoded() {
    for call in ["json.encode(hasher)", "csv.encode(hasher)"] {
        let e = errors_of(&["- sha2 sha256_new -> hasher", &format!("- set text = {call}")]);
        assert!(!e.is_empty(), "{call} must be refused");
    }
}

#[test]
fn json_parse_cannot_produce_a_handle() {
    let e = errors_of(&["- try json.parse(word) as handle of sha2.Sha256 -> h"]);
    assert!(e.contains("cannot read") && e.contains("handle"), "{e}");
    let e = errors_of(&["- try do csv.parse(word) as list of handle of sha2.Sha256 -> h"]);
    assert!(!e.is_empty(), "{e}");
}

#[test]
fn csv_encode_wants_records() {
    let e = errors_of(&["- set rows = csv.encode(word)"]);
    assert!(e.contains("must be a list"), "{e}");
}
