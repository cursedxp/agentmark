static TURN: tokio::sync::Mutex<()> = tokio::sync::Mutex::const_new(());

async fn guarded<F>(ctx: &Ctx, unit: &str, label: &str, seconds: u64, run: F) -> bool
where
    F: std::future::Future<Output = Result<(), AgentError>>,
{
    let _turn = TURN.lock().await;
    let problem = match tokio::time::timeout(std::time::Duration::from_secs(seconds), run).await {
        Ok(Ok(())) => return true,
        Ok(Err(e)) => e.to_string(),
        Err(_) => format!("timed out after {seconds} seconds"),
    };
    eprintln!("{unit} / {label}: {problem}");
    if let Err(e) = ctx.enter(unit, label).trace_error(&problem) {
        eprintln!("trace: {e}");
    }
    false
}

